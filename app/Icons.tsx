/** チャンネルタイプまたはアイコン名からアイコンを返すヘルパー */
export function ChannelIcon({ type, iconName, size = 18 }: { type: string; iconName?: string | null; size?: number }) {
  const name = (iconName || type).toLowerCase();
  
  // 1. まずは既存のカスタムアイコンをチェック
  switch (name) {
    case 'guide': return <IconGuide size={size} />;
    case 'chat': return <IconChat size={size} />;
    case 'material': {
      const FileText = LucideIcons.FileText;
      return <FileText size={size} />;
    }
    case 'lesson_record': return <IconNotepad size={size} />;
    case 'booking': return <IconCalendar size={size} />;
    case 'memo': return <IconMemo size={size} />;
    case 'dashboard': return <IconDashboard size={size} />;
    case 'youtube': return <IconYoutube size={size} />;
  }

  // 2. LucideIcons に存在する場合はそれを返す
  // e.g. "smile" -> "Smile", "message_circle" -> "MessageCircle"
  const lucideName = name.split('_').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join('');
  const LucideIcon = (LucideIcons as unknown as Record<string, React.FC<LucideProps>>)[lucideName];
  if (LucideIcon) {
    return <LucideIcon size={size} strokeWidth={2} />;
  }

  // デフォルト
  return <IconHash size={size} />;
}

